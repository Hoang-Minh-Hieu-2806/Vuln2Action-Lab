"""Build a group-disjoint T5 split manifest from a flow dataset.

This script only writes manifest/report files into --output-dir. It never edits
the source dataset or starts training. Intended to be run after a real dataset is
available; no output is generated by writing this script.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
from collections import defaultdict
from difflib import SequenceMatcher
from pathlib import Path


def _normalise(text: str) -> str:
    text = re.sub(r"^\s*\d+[.):]\s*", "", text.lower())
    return " ".join(text.split())


def _find(parent: list[int], item: int) -> int:
    while parent[item] != item:
        parent[item] = parent[parent[item]]
        item = parent[item]
    return item


def _union(parent: list[int], left: int, right: int) -> None:
    left_root, right_root = _find(parent, left), _find(parent, right)
    if left_root != right_root:
        parent[max(left_root, right_root)] = min(left_root, right_root)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", required=True, help="JSONL file with a target field")
    parser.add_argument("--target-field", default="target")
    parser.add_argument("--output-dir", required=True)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--threshold", type=float, default=0.85)
    parser.add_argument("--validation-ratio", type=float, default=0.1)
    parser.add_argument("--test-ratio", type=float, default=0.1)
    args = parser.parse_args()

    source = Path(args.dataset)
    if not source.is_file():
        parser.error(f"dataset not found: {source}")
    if not 0.0 < args.threshold <= 1.0:
        parser.error("threshold must be in (0, 1]")

    rows = [
        json.loads(line) for line in source.read_text(encoding="utf-8").splitlines() if line.strip()
    ]
    targets = [_normalise(str(row.get(args.target_field) or "")) for row in rows]
    if len(rows) < 3:
        parser.error("need at least 3 rows for train/validation/test")

    parent = list(range(len(rows)))
    exact_groups: dict[str, list[int]] = defaultdict(list)
    for index, target in enumerate(targets):
        exact_groups[target].append(index)
    exact_duplicate_groups = sum(1 for indices in exact_groups.values() if len(indices) > 1)
    for indices in exact_groups.values():
        for index in indices[1:]:
            _union(parent, indices[0], index)

    buckets: dict[str, list[int]] = defaultdict(list)
    for index, target in enumerate(targets):
        key = " ".join(target.split()[:3]) or target[:40]
        buckets[key].append(index)
    near_pairs = 0
    for indices in buckets.values():
        for position, left in enumerate(indices):
            for right in indices[position + 1 :]:
                if _find(parent, left) == _find(parent, right):
                    continue
                if SequenceMatcher(None, targets[left], targets[right]).ratio() >= args.threshold:
                    _union(parent, left, right)
                    near_pairs += 1

    grouped: dict[int, list[int]] = defaultdict(list)
    for index in range(len(rows)):
        grouped[_find(parent, index)].append(index)
    group_ids = sorted(grouped)
    if len(group_ids) < 3:
        parser.error("fewer than 3 distinct groups after deduplication")

    order = list(group_ids)
    random.Random(args.seed).shuffle(order)
    test_size = max(1, int(len(order) * args.test_ratio))
    validation_size = max(1, int(len(order) * args.validation_ratio))
    test = set(order[:test_size])
    validation = set(order[test_size : test_size + validation_size])
    train = set(order[test_size + validation_size :])
    assert not train & validation and not train & test and not validation & test

    assignment = {"train": [], "validation": [], "test": []}
    for group_id, indices in grouped.items():
        split = "train" if group_id in train else "validation" if group_id in validation else "test"
        for index in indices:
            assignment[split].append(
                {
                    "cve_id": rows[index].get("cve_id"),
                    "target": targets[index],
                    "group_id": group_id,
                }
            )

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    manifest = {
        "source": str(source),
        "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "target_field": args.target_field,
        "seed": args.seed,
        "threshold": args.threshold,
        "groups": len(group_ids),
        "splits": {name: [row["cve_id"] for row in values] for name, values in assignment.items()},
    }
    (out / "split_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (out / "split_assignments.jsonl").write_text(
        "".join(
            json.dumps({**row, "split": name}, ensure_ascii=False) + "\n"
            for name, values in assignment.items()
            for row in values
        ),
        encoding="utf-8",
    )
    leakage = {
        "exact_duplicate_groups": exact_duplicate_groups,
        "near_duplicate_pairs_merged": near_pairs,
        "shared_groups_train_validation": len(train & validation),
        "shared_groups_train_test": len(train & test),
        "shared_groups_validation_test": len(validation & test),
        "status": "GROUP_DISJOINT"
        if not (train & validation or train & test or validation & test)
        else "FAILED",
    }
    (out / "leakage_report.json").write_text(
        json.dumps(leakage, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"groups={len(group_ids)} status={leakage['status']} out={out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
